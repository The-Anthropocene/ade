def ade_cmd():
    """`ade` when PATH's ade runs this same kit, so the hooks read short. Otherwise the absolute path of the ade that
    is running: an install kept off PATH (a shared machine whose shell profile stays untouched) still gets working hooks,
    and a different ade first on PATH (a dev checkout ahead of the pinned venv) never runs them in this kit's place.
    The hooks live in the gitignored settings.local.json, so each machine's `ade init` writes its own form."""
    found = shutil.which("ade")
    return "ade" if found and _this_kit(found) else launcher()


def _this_kit(found):
    # PATH's ade is this kit when it resolves to this kit's bin/ade or to the running launcher, or is a small script
    # (an `ade link` shim, a pip console script) naming that launcher or this kit's python.
    p, me = Path(found).resolve(), launcher()
    if p == Path(__file__).resolve().parent.parent / "bin" / "ade" or f'"{p.as_posix()}"' == me:
        return True
    try:
        text = p.read_text(errors="replace") if p.stat().st_size < 4000 else ""
    except OSError:
        return False
    first = text.split("\n", 1)[0]
    py = first[2:].strip().split(" ")[0] if first.startswith("#!") else ""
    # `#!/usr/bin/env python3` names no particular python (a dev checkout's bin/ade), so it never matches.
    named = Path(py).name.startswith("python") and Path(py).parent == Path(sys.executable).parent
    return me in text or (named and "from ade" in text)


def kit():
    """The kit this process runs, as text: its version, plus the git commit when the kit is a checkout."""
    root = Path(__file__).resolve().parent.parent
    try:
        version = tomllib.loads(host.read(root / "pyproject.toml"))["project"]["version"]
    except (OSError, KeyError, tomllib.TOMLDecodeError):  # an installed wheel has no pyproject.toml: ask pip's metadata
        try:
            version = importlib.metadata.version("atlas-ade")
        except importlib.metadata.PackageNotFoundError:
            version = "unknown"
    commit = ""
    if (root / ".git").exists() and shutil.which("git"):  # no git on PATH (the demo's install leg): version alone
        head = git(root, "rev-parse", "--short", "HEAD", check=False)
        commit = head.stdout.strip() if head.returncode == 0 else ""
    return f"{version} ({commit})" if commit else version


def launcher():
    """The absolute, quoted command for the ade that is running: the portable bundle's launcher (which sets
    ADE_LAUNCHER), its own script, or its python with -m ade."""
    bundled = os.environ.get("ADE_LAUNCHER")
    if bundled and Path(bundled).is_file():
        return f'"{Path(bundled).as_posix()}"'
    me = Path(sys.argv[0]).resolve()
    for exe in (me, me.with_suffix(".exe")):
        if exe.stem == "ade" and exe.is_file():
            return f'"{exe.as_posix()}"'
    return f'"{Path(sys.executable).as_posix()}" -m ade'


def _ours(cmd):
    # Any form ade_cmd() ever wrote, or an earlier install's kit path (`'/path/to/kit/bin/ade' hook brief`).
    cmd = cmd.strip()
    q = cmd[:1] if cmd[:1] in "'\"" else ""
    first, _, rest = cmd[1:].partition(q) if q else cmd.partition(" ")  # an unbalanced quote leaves rest empty
    words = rest.split()
    # ADE's own verbs only: a person's ./scripts/ade.sh lint is not ours.
    return bool(words) and words[0] in ("hook", "status") and Path(first.replace("\\", "/")).name in ("ade", "ade.exe", "ade.cmd") \
        or words[:2] == ["-m", "ade"]


def _denied(ctx):
    """deny rules init owns: ade.toml's, plus Read() and Grep() of each [guards] secrets glob. Claude Code reads a rule
    path ~/x as home and //x as absolute, so those (and /x, written //x) stay put; a bare glob is denied under home
    (~/glob) and at any depth under the project (**/glob), as hook 2 matches it anywhere."""
    pats = []
    # A deny beats any allow and cannot carry an exception, so a secrets glob a tracked: secret_ok glob overlaps loses its
    # static deny and `hook read` judges it instead (the same secret/secret_ok test as the bash guard).
    tr = [t[len("tracked:"):] for t in ctx.cfg["guards"]["secret_ok"] if t.startswith("tracked:")]
    for g in ctx.cfg["guards"]["secrets"]:
        if any(fnmatch.fnmatchcase(a, b) for t in tr for a, b in ((g, t), (t, g))):
            continue
        g = g.removeprefix("./")
        pats += [g] if g.startswith(("~/", "//")) else ["/" + g] if g.startswith("/") else ["~/" + g, "**/" + g]
    return list(ctx.cfg["permissions"]["deny"]) + [f"{t}({g})" for g in pats for t in ("Read", "Grep")]


def removed(ctx, existing):
    """The (kind, rule) pairs in settings.json that ade.toml no longer has; init drops them."""
    perms = existing.get("permissions", {})
    own = {"allow": list(ctx.cfg["permissions"]["allow"]), "deny": _denied(ctx)}
    return [(kind, r) for kind in own for r in perms.get(kind, []) if r not in own[kind]]


def settings(ctx, existing):
    """The committed .claude/settings.json: permissions only, identical on every machine. Hooks and the status line
    name how this machine reaches ade, so they live in settings.local.json; any left here by an older init go."""
    out = dict(existing)
    perms = dict(out.get("permissions", {}))
    for kind in ("allow", "deny"):
        perms[kind] = list(_denied(ctx) if kind == "deny" else ctx.cfg["permissions"][kind])
    # Never widen the mode the user chose; only fill it in when absent, and only when ade.toml names one.
    mode = ctx.cfg["permissions"]["mode"]
    if mode:
        perms.setdefault("defaultMode", mode)
    out["permissions"] = perms
    # The platform's own cap on Bash output (ARCHITECTURE.md 12.5); a value the user set is never replaced.
    if ctx.cfg["q"]["bash_chars"] and "BASH_MAX_OUTPUT_LENGTH" not in out.get("env", {}):
        out["env"] = {**out.get("env", {}), "BASH_MAX_OUTPUT_LENGTH": str(ctx.cfg["q"]["bash_chars"])}
    if _ours(out.get("statusLine", {}).get("command", "")):
        del out["statusLine"]
    hooks = _strip(out.get("hooks", {}))
    out.pop("hooks", None)
    if hooks:
        out["hooks"] = hooks
    return out


def _strip(hooks):
    # Only ADE's hooks leave a matcher group; the person's beside them stay, and a group left empty goes.
    kept = {k: [{**e, "hooks": mine} for e in v if (mine := [h for h in e.get("hooks", []) if not _ours(h.get("command", ""))])]
            for k, v in hooks.items()}
    return {k: v for k, v in kept.items() if v}


def _add_hooks(existing):
    """`existing` with ADE's HOOKS (this machine's ade_cmd()) merged beside the user's own entries, ours stripped first."""
    out, cmd = dict(existing), ade_cmd()
    hooks = _strip(out.get("hooks", {}))
    for event, matcher, verb in HOOKS:
        entry = {"hooks": [{"type": "command", "command": f"{cmd} {verb}"}]}
        hooks.setdefault(event, []).append({"matcher": matcher, **entry} if matcher else entry)
    out["hooks"] = hooks
    return out


def local_settings(existing):
    """The gitignored .claude/settings.local.json: ade's hooks and status line in this machine's form of ade_cmd(),
    merged into whatever the user keeps there (Claude Code writes its own local approvals to the same file)."""
    out = _add_hooks(existing)
    if "statusLine" not in out or _ours(out["statusLine"].get("command", "")):  # the person's own stays
        out["statusLine"] = {"type": "command", "command": f"{ade_cmd()} status --line"}
    return out


def codex_hooks(existing):
    """The gitignored .codex/hooks.json: the same HOOKS set as settings.local.json, in Claude's hooks shape, merged
    beside the user's entries. Proven on Codex 0.167: SessionStart, PreToolUse and Stop fire; PostToolUse is unproven.
    Codex runs them only after a one-time hook trust in the Codex TUI, separate from folder trust; whether a lane ever
    passes a hook-trust bypass is a person's security call, and no ADE code passes one."""
    return _add_hooks(existing)


def _snake(ev):
    return re.sub("(?<!^)(?=[A-Z])", "_", ev).lower()


def codex_flags():
    """ADE's HOOKS as Codex `-c hooks.<Event>=[...]` argv pieces, in HOOKS order with this machine's ade_cmd(), so the
    same machine always prints the same bytes: Codex keys hook trust by event and group/hook index, and a key built from
    session flags is path-free, so one accept per machine covers every lane. ADE never accepts for the person."""
    by, cmd = {}, ade_cmd()
    for event, matcher, verb in HOOKS:
        h = f'hooks = [{{ type = "command", command = {json.dumps(f"{cmd} {verb}")} }}]'
        by.setdefault(event, []).append("{ " + (f"matcher = {json.dumps(matcher)}, " if matcher else "") + h + " }")
    return [a for ev, groups in by.items() for a in ("-c", f"hooks.{ev}=[{', '.join(groups)}]")]


def codex_open_command():
    """The one command that opens Codex with ADE's hook flags, for the person to accept ('Trust all and continue') once."""
    return "codex " + " ".join(shlex.quote(a) for a in codex_flags())


def _hook_hashes(event, matcher, command):
    """Codex's hook_hash (sha256 over key-sorted compact JSON) of one hook, with the matcher and without it; the
    matcher-less form is what a real key accepted under codex 0.160 matched."""
    body = {"event_name": _snake(event), "hooks": [{"type": "command", "command": command, "timeout": 600, "async": False}]}
    return {"sha256:" + hashlib.sha256(json.dumps(b, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()).hexdigest()
            for b in ([body, {**body, "matcher": matcher}] if matcher else [body])}


def codex_untrusted(ctx):
    """What Codex's config.toml ([hooks.state] under CODEX_HOME, default ~/.codex) lacks, as
    {'sessions': [...], 'lanes': [...], 'different': [...]}: 'sessions' are the (event, group, hook) indexes of ADE's
    entries in the repo's .codex/hooks.json (the person's own interactive Codex), keyed by path; 'lanes' are the
    session-flag keys of codex_flags() (lanes); 'different' are keys present whose trusted_hash is not the hash of ADE's
    hook. A key with no trusted_hash counts as present. None when unparsable. Keys match case-insensitively, / and
    backslash alike."""
    flat = lambda t: re.sub(r"[\\/]+", "/", t).lower()
    p = Path(os.environ.get("CODEX_HOME") or Path.home() / ".codex") / "config.toml"
    try:
        state = tomllib.loads(host.read(p)).get("hooks", {}).get("state", {}) if p.is_file() else {}
        f = ctx.root / CODEX
        hooks = json.loads(host.read(f)).get("hooks", {}) if f.is_file() else {}
    except (ValueError, OSError):
        return None
    have = {flat(k): v for k, v in state.items()}
    where = flat(str(ctx.root / CODEX))
    cmd, out = ade_cmd(), {"sessions": [], "lanes": [], "different": []}

    def check(key, ev, matcher, command):  # True when the key is present; a foreign hash is also named in 'different'
        if key not in have:
            return False
        h = have[key].get("trusted_hash") if isinstance(have[key], dict) else None
        if h is not None and h not in _hook_hashes(ev, matcher, command):
            out["different"].append(key)
        return True

    for ev, groups in hooks.items():
        for g, e in enumerate(groups):
            for i, h in enumerate(e.get("hooks", [])):
                if _ours(h.get("command", "")) and not check(f"{where}:{_snake(ev)}:{g}:{i}", ev, e.get("matcher"), h["command"]):
                    out["sessions"].append((ev, g, i))
    seen = {}
    for event, matcher, verb in HOOKS:
        g = seen[event] = seen.get(event, -1) + 1
        key = f"/<session-flags>/config.toml:{_snake(event)}:{g}:0"
        if not check(key, event, matcher, f"{cmd} {verb}"):
            out["lanes"].append(key)
    return out


