def _gitignore(existing):
    have = existing.splitlines()
    # The flight band is a per-machine copy of a kit mod: ignored, so no graph build (init's or land's) ever sees it.
    add = [x for x in (".ade/", "__pycache__/", LOCAL, CODEX, BAND_DST + "/") if x not in have]
    return existing if not add else (existing.rstrip("\n") + "\n" if existing.strip() else "") + "\n".join(add) + "\n"


def _adapters(ctx):
    # Only the adapters of engines some role or profile uses (a profile's models name its engines).
    used = engines(ctx) | {e for r in ctx.cfg["roles"].values() for p in r.get("profiles", {}).values() for e in p.get("models", {})}
    return {s: d for s, d in ADAPTERS.items() if s.split("-")[0] in used}


def _lf(ctx):
    # Generated files stay LF on every checkout, Windows included, so regenerating them never shows a diff.
    return [f"{p} text eol=lf" for p in (ctx.cfg["graph"]["out"], ".claude/settings.json", ".claude/agents/*.md", "AGENTS.md", *_adapters(ctx).values())]


def _gitattributes(ctx, existing):
    have = existing.splitlines()
    add = [x for x in _lf(ctx) if x not in have]
    return existing if not add else (existing.rstrip("\n") + "\n" if existing.strip() else "") + "\n".join(add) + "\n"


def _json(d):
    return json.dumps(d, indent=2) + "\n" if d else None


def removal(ctx):
    """What `ade uninstall` changes, as (relative path, text, or None to delete): everything init generated, and
    only that. ade.toml, .ade/ (records) and the ade-records branch stay; they are the user's, not generated."""
    def cur(rel):
        p = ctx.root / rel
        return host.read(p) if p.is_file() else None

    out = []
    s = json.loads(cur(".claude/settings.json") or "{}")
    perms = dict(s.get("permissions", {}))
    for kind in ("allow", "deny"):
        own = _denied(ctx) if kind == "deny" else ctx.cfg["permissions"][kind]
        kept = [r for r in perms.get(kind, []) if r not in own]
        perms.pop(kind, None)
        perms.update({kind: kept} if kept else {})
    if ctx.cfg["permissions"]["mode"] and perms.get("defaultMode") == ctx.cfg["permissions"]["mode"]:
        del perms["defaultMode"]  # the mode ade.toml names, which init filled in; any other is the user's and stays
    s.pop("permissions", None)
    s.update({"permissions": perms} if perms else {})
    local = json.loads(cur(LOCAL) or "{}")
    for d in (s, local):  # settings.json too: an older init put hooks there
        if _ours(d.get("statusLine", {}).get("command", "")):
            del d["statusLine"]
        hooks = _strip(d.pop("hooks", {}))
        d.update({"hooks": hooks} if hooks else {})
    codex = json.loads(cur(CODEX) or "{}")
    hooks = _strip(codex.pop("hooks", {}))
    codex.update({"hooks": hooks} if hooks else {})
    out += [(".claude/settings.json", _json(s)), (LOCAL, _json(local)), (CODEX, _json(codex))]
    out += [(f".claude/agents/ade-{n}.md", None) for n in ctx.cfg["roles"]] + [(SKILL, None), (SKILL_CODEX, None)]
    out += [(dst, None) for dst in (*ADAPTERS.values(), *(f"{BAND_DST}/{r}" for r in BAND_FILES))]
    agents = cur("AGENTS.md") or ""
    if BEGIN in agents and END in agents:
        head, rest = agents.split(BEGIN, 1)
        agents = (head.rstrip() + "\n\n" + rest.split(END, 1)[1].lstrip()).strip()
        out.append(("AGENTS.md", agents + "\n" if agents else None))
    attrs = "".join(x + "\n" for x in (cur(".gitattributes") or "").splitlines() if x not in _lf(ctx))
    out += [(".gitattributes", attrs or None), (ctx.cfg["graph"]["out"], None)]
    out += [(MIRROR, None)] if (cur(MIRROR) or "").startswith("# Generated by ade init") else []
    return [(rel, new) for rel, new in out if new != cur(rel)]


