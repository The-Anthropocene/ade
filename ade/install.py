def mirror_workflow(ctx):
    """GitHub moves each mirror's dst after a push of its src, so no machine pushes it (a push of a deploy-looking
    branch is what an agent's safety check rightly stops). No `+`: a dst holding commits src lacks fails the job."""
    pairs = push.mirror_pairs(ctx.cfg)
    steps = "".join(f'      - if: github.ref == \'refs/heads/{s}\'\n        run: git push origin "$GITHUB_SHA:refs/heads/{d}"\n'
                    for s, d in pairs)
    return ("# Generated by ade init from [git] mirror in ade.toml; edit that, then rerun ade init.\n"
            "# Fast-forward only. A push made with GITHUB_TOKEN starts no other workflow, so CI must run on the source.\n"
            "name: ade mirror\n\non:\n  push:\n    branches: [" + ", ".join(sorted({s for s, _ in pairs})) + "]\n\n"
            "permissions:\n  contents: write\n\nconcurrency:\n  group: ade-mirror\n  cancel-in-progress: false\n\n"
            "jobs:\n  mirror:\n    runs-on: ubuntu-latest\n    timeout-minutes: 5\n    steps:\n"
            "      - uses: actions/checkout@v4\n        with:\n          fetch-depth: 0\n" + steps)


def first_toml(root):
    # The first ade.toml fits the repo it lands in: its trunk, mirrors, deploy triggers and deps (ade.survey).
    from ade import firstrun  # here, not at the top, as for providers in config
    return firstrun.chosen(survey.apply(host.read(TEMPLATE), survey.survey(root)[1]))


def plan(ctx):
    """Every file init owns, as (relative path, desired text)."""
    def cur(rel):
        p = ctx.root / rel
        return host.read(p) if p.is_file() else ""

    files = [("ade.toml", cur("ade.toml") or first_toml(ctx.root)), (".gitignore", _gitignore(cur(".gitignore"))),
             (".gitattributes", _gitattributes(ctx, cur(".gitattributes")))]
    existing = json.loads(cur(".claude/settings.json") or "{}")
    files.append((".claude/settings.json", json.dumps(settings(ctx, existing), indent=2) + "\n"))
    local = json.loads(cur(LOCAL) or "{}")
    if "statusLine" in local and not _ours(local["statusLine"].get("command", "")) and not getattr(plan, "said", 0):
        plan.said = print("kept your own status line in .claude/settings.local.json") or 1
    files.append((LOCAL, json.dumps(local_settings(local), indent=2) + "\n"))
    files.append((CODEX, json.dumps(codex_hooks(json.loads(cur(CODEX) or "{}")), indent=2) + "\n"))
    files += [(f".claude/agents/ade-{n}.md", _agent(n, r)) for n, r in ctx.cfg["roles"].items()]
    files.append(("AGENTS.md", _agents_md(ctx, cur("AGENTS.md"))))
    files += [(SKILL, skill()), (SKILL_CODEX, skill())]
    files += [(f"{BAND_DST}/{r}", host.read(BAND_SRC / r)) for r in BAND_FILES]
    for src, dst in ADAPTERS.items():
        text = host.read(Path(__file__).resolve().parent / "starters" / "harness" / src)
        if dst in _adapters(ctx).values():  # another engine's existing file stays: a teammate may use it; only uninstall removes it
            files.append((dst, text))
    if push.mirror_pairs(ctx.cfg) and push.on_github(ctx.root, ctx.cfg["git"]["remote"]):
        files.append((MIRROR, mirror_workflow(ctx)))
    files.append((ctx.cfg["graph"]["out"], graph.render(graph.build(ctx.root, ctx.cfg))))
    skip = parts.files_off(ctx.cfg)  # an off part's generated files are not written
    return [(rel, text) for rel, text in files if rel not in skip]
